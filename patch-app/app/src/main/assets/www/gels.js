/* xyY sous source C → sRGB. Adaptation Bradford vers D65, puis la
   chromaticité est poussée à pleine intensité et assombrie selon la
   transmission, adoucie pour qu'un bleu nuit ne tombe pas au noir. */
const mulM = (m, v) => m.map(r => r[0]*v[0] + r[1]*v[1] + r[2]*v[2]);
const xyVersXYZ = (x, y, Y = 1) => [x * Y / y, Y, (1 - x - y) * Y / y];
const BRADFORD = [[0.8951,0.2664,-0.1614],[-0.7502,1.7135,0.0367],[0.0389,-0.0685,1.0296]];
const BRADFORD_INV = [[0.9869929,-0.1470543,0.1599627],[0.4323053,0.5183603,0.0492912],[-0.0085287,0.0400428,0.9684867]];
const VERS_SRGB = [[3.2406,-1.5372,-0.4986],[-0.9689,1.8758,0.0415],[0.0557,-0.2040,1.0570]];
const BLANC_C = xyVersXYZ(0.3101, 0.3162), BLANC_D65 = xyVersXYZ(0.3127, 0.3290);
const CONE_C = mulM(BRADFORD, BLANC_C), CONE_D65 = mulM(BRADFORD, BLANC_D65);
function hexDeXy(x, y, Y){
  const c = mulM(BRADFORD, xyVersXYZ(x, y)).map((v, i) => v * CONE_D65[i] / CONE_C[i]);
  const l = mulM(VERS_SRGB, mulM(BRADFORD_INV, c)).map(v => Math.max(0, v));
  const k = (0.25 + 0.75 * Math.pow(Y / 100, 0.35)) / Math.max(...l);
  const g = v => v <= 0.0031308 ? 12.92 * v : 1.055 * Math.pow(v, 1 / 2.4) - 0.055;
  return "#" + l.map(v => Math.round(g(Math.min(1, v * k)) * 255)
    .toString(16).padStart(2, "0")).join("").toUpperCase();
}
/* CIELAB sous source C, pour classer les teintes proches (ΔE 76). */
function labDeXy(x, y, Y){
  const f = t => t > 0.008856 ? Math.cbrt(t) : 7.787 * t + 16 / 116;
  const [X, Yy, Z] = xyVersXYZ(x, y, Y / 100);
  const fx = f(X / BLANC_C[0]), fy = f(Yy), fz = f(Z / BLANC_C[2]);
  return [116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)];
}

const MARQUES_GEL = { L:"Lee", G:"GAM", R:"Rosco" };
const GELS = (() => {
  const lee = LEE_XY.map(([ref, nom, x, y, Y]) =>
    ({ ref, nom, m:"L", Y, hex:hexDeXy(x, y, Y), lab:labDeXy(x, y, Y), eq:[] }));
  const parRef = Object.fromEntries(lee.map(g => [g.ref, g]));
  const autres = (m, liste) => liste.map(([ref, nom, eq]) => {
    const e = eq ? eq.split(" ").map(n => "L" + n).filter(r => parRef[r]) : [];
    return { ref, nom, m, eq:e, hex:e.length ? parRef[e[0]].hex : null };
  });
  const tous = [...lee, ...autres("G", GAM_EQ), ...autres("R", ROSCO_EQ)];
  /* Le sens inverse : depuis un Lee, les GAM et Rosco qui l'annoncent. */
  tous.forEach(g => g.eq.forEach(r => { if(g.m !== "L") parRef[r].eq.push(g.ref); }));
  return tous;
})();
const GEL_PAR_REF = Object.fromEntries(GELS.map(g => [g.ref, g]));

/* Les Lee les plus proches d'un Lee, par écart de couleur. */
function leeProches(g, n = 4){
  if(!g.lab) return [];
  const d = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2]);
  return GELS.filter(x => x.m === "L" && x !== g)
    .map(x => ({ g:x, de:d(g.lab, x.lab) }))
    .sort((a, b) => a.de - b.de).slice(0, n);
}
